export const PICTURE_IDS = Object.keys(PICTURE_ZH);

const BY_ZH = new Map<string, string>();
for (const [id, zh] of Object.entries(PICTURE_ZH)) for (const z of zh) if (!BY_ZH.has(z)) BY_ZH.set(z, id);

/** 一個意思對應的圖片 id（沒有就是 undefined） */
export function pictureOf(meaning: string): string | undefined {
  for (const part of meaning.split(/[；;、，,/／（）()]/)) {
    const id = BY_ZH.get(part.trim());
    if (id) return id;
  }
  return undefined;
}

/** 圖片的中文名稱（選項答錯時顯示） */
export const pictureName = (id: string): string => PICTURE_ZH[id]?.[0] ?? '';
