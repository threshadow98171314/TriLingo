export function koConjExplain(v: KoVerb): string {
  const rule = LOOKALIKE[v.dict] ?? RULE[v.type] ?? RULE['規則'];
  return `${v.dict} → ${v.present}（過去 ${v.past}）。${rule}`;
}

export function koConjQuestions(rng: Rng, mode: string, n: number): DrillQ[] {
  const pool = mode === 'irregular' ? KO_VERBS.filter((v) => v.type !== '規則' && v.type !== '하다') : KO_VERBS;
  const out: DrillQ[] = [];
  const used = new Set<string>();
  for (let guard = 0; out.length < n && guard < n * 50; guard++) {
    const v = pick(pool, rng);
    const past = mode === 'past' ? true : mode === 'present' ? false : rng() < 0.4;
    const key = `${v.dict}${past}`;
    if (used.has(key)) continue;
    used.add(key);
    const right = past ? v.past : v.present;
    const wrong = [...new Set(past ? v.wrong.map(toPast) : v.wrong)].filter((x) => x !== right);
    out.push({
      prompt: v.dict,
      hint: `${v.m}・${past ? '過去（-았어요／었어요）' : '現在（-아요／어요）'}`,
      opts: [right, ...sample(wrong, 3, rng)],
      explain: koConjExplain(v),
      say: right,
    });
  }
  return out;
}
