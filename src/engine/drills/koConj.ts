export const KO_VERBS: KoVerb[] = RAW.trim()
  .split('\n')
  .map((line) => {
    const [dict, m, type, present, past, wrong] = line.trim().split('|');
    return { dict, m, type, present, past, wrong: wrong.split(' ') };
  });

/** 「X요」→「X(ㅆ)어요」：在요前面的音節加上收尾音ㅆ，例如 덥어요 → 덥었어요 */
export function toPast(present: string): string {
  const body = present.slice(0, -1);
  const last = body.charCodeAt(body.length - 1) - 0xac00;
  if (last < 0 || last > 11171 || last % 28 !== 0) return `${body}었어요`;
  return `${body.slice(0, -1)}${String.fromCharCode(0xac00 + last + 20)}어요`;
}

